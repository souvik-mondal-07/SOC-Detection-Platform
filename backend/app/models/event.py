"""Security event schemas: incoming (API), stored (MongoDB) and API responses."""

from enum import Enum
from typing import Annotated, Any

from pydantic import BaseModel, BeforeValidator, ConfigDict, Field, field_validator

from app.models.common import (
    ID_PATTERN,
    SNAKE_CASE_PATTERN,
    IPAddressStr,
    MongoModel,
    UTCDateTime,
    utc_now,
    validate_metadata,
)
from app.models.normalization import (
    blank_to_none,
    normalize_action,
    normalize_event_type,
    normalize_source,
    normalize_status,
    normalize_status_or_unknown,
    prepare_timestamp,
)

MAX_BATCH_SIZE = 500
MAX_PAGE_SIZE = 500


class SourceType(str, Enum):
    """Logical source categories (not real log collectors)."""

    LINUX_AUTH = "linux_auth"
    WINDOWS_EVENT = "windows_event"
    WEB_APPLICATION = "web_application"
    NETWORK = "network"
    APPLICATION = "application"


class EventType(str, Enum):
    AUTHENTICATION = "authentication"
    WEB = "web"
    NETWORK = "network"
    PRIVILEGE = "privilege"
    SYSTEM = "system"
    APPLICATION = "application"


class EventStatus(str, Enum):
    SUCCESS = "success"
    FAILED = "failed"
    BLOCKED = "blocked"
    UNKNOWN = "unknown"  # neutral value when the outcome is not meaningful or not known


# ---------------------------------------------------------------- stored event

class SecurityEvent(MongoModel):
    """A normalised event as stored in MongoDB and returned by the API.

    `source` accepts any snake_case value (not only SourceType) so documents
    written by earlier steps stay readable. New events are restricted to
    SourceType by EventCreate.
    """

    event_id: str = Field(pattern=ID_PATTERN)
    timestamp: UTCDateTime
    source: str = Field(pattern=SNAKE_CASE_PATTERN)
    event_type: EventType
    action: str = Field(pattern=SNAKE_CASE_PATTERN)
    status: EventStatus
    username: str | None = Field(default=None, min_length=1, max_length=64)
    source_ip: IPAddressStr | None = None
    message: str = Field(min_length=1, max_length=1000)
    # Extensible, source-specific extras. Credential-like keys are rejected.
    metadata: dict[str, Any] = Field(default_factory=dict)
    created_at: UTCDateTime = Field(default_factory=utc_now)

    @field_validator("metadata")
    @classmethod
    def _metadata_is_safe(cls, value: dict[str, Any]) -> dict[str, Any]:
        return validate_metadata(value)


# ---------------------------------------------------------------- incoming event

class EventCreate(MongoModel):
    """Incoming event. Normalisation runs before validation, so "FAILED" and "Auth" are accepted.

    event_id and created_at are always generated by the server and cannot be supplied.
    """

    timestamp: Annotated[UTCDateTime | None, BeforeValidator(prepare_timestamp)] = None
    source: Annotated[SourceType, BeforeValidator(normalize_source)]
    event_type: Annotated[EventType, BeforeValidator(normalize_event_type)]
    action: Annotated[str, BeforeValidator(normalize_action)] = Field(pattern=SNAKE_CASE_PATTERN)
    status: Annotated[EventStatus, BeforeValidator(normalize_status_or_unknown)] = EventStatus.UNKNOWN
    username: Annotated[str | None, BeforeValidator(blank_to_none)] = Field(default=None, min_length=1, max_length=64)
    source_ip: Annotated[IPAddressStr | None, BeforeValidator(blank_to_none)] = None
    message: str = Field(min_length=1, max_length=1000)
    metadata: dict[str, Any] = Field(default_factory=dict)

    @field_validator("metadata")
    @classmethod
    def _metadata_is_safe(cls, value: dict[str, Any]) -> dict[str, Any]:
        return validate_metadata(value)

    model_config = ConfigDict(
        extra="forbid",
        use_enum_values=True,
        validate_default=True,
        str_strip_whitespace=True,
        json_schema_extra={
            "examples": [
                {
                    "timestamp": "2026-10-02T10:15:23Z",
                    "source": "linux_auth",
                    "event_type": "authentication",
                    "action": "login",
                    "status": "failed",
                    "username": "test_user",
                    "source_ip": "192.168.1.20",
                    "message": "Failed password for test_user",
                    "metadata": {},
                }
            ]
        },
    )


class EventQuery(MongoModel):
    """Query parameters for GET /events. Values are normalised like incoming events."""

    limit: int = Field(default=50, ge=1, le=MAX_PAGE_SIZE)
    source: Annotated[SourceType | None, BeforeValidator(normalize_source)] = None
    event_type: Annotated[EventType | None, BeforeValidator(normalize_event_type)] = None
    status: Annotated[EventStatus | None, BeforeValidator(normalize_status)] = None
    source_ip: Annotated[IPAddressStr | None, BeforeValidator(blank_to_none)] = None


# ---------------------------------------------------------------- API responses

class EventIngestResponse(BaseModel):
    success: bool = True
    message: str
    event: SecurityEvent


class EventListResponse(BaseModel):
    count: int
    events: list[SecurityEvent]


class BatchEventRequest(BaseModel):
    """Items are validated one by one by the service, so one bad event does not reject the rest."""

    model_config = ConfigDict(extra="forbid")

    events: list[Any] = Field(min_length=1, max_length=MAX_BATCH_SIZE)


class FieldError(BaseModel):
    field: str
    message: str


class BatchItemError(BaseModel):
    index: int  # position in the submitted list, starting at 0
    errors: list[FieldError]


class BatchIngestResponse(BaseModel):
    success: bool  # True only when every event was accepted
    message: str
    accepted: int
    rejected: int
    event_ids: list[str]  # IDs of accepted events, in submission order
    errors: list[BatchItemError]
